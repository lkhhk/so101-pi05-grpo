import argparse
import fcntl
import hashlib
import json
import os
import os
from pathlib import Path
import re
import signal
import subprocess
import sys
import time

SCRIPTS = Path(__file__).resolve().parent
PROJECT = SCRIPTS.parent
CONFIG = PROJECT / "configs"
ROOT = Path(os.getenv("SO101_RUN_DIR", PROJECT / "runs/blockbox")).resolve()
BASE = Path(os.getenv("SO101_BASE", PROJECT / "models/ira-base")).resolve()
TOKENIZER = Path(os.getenv("SO101_TOKENIZER", PROJECT / "models/paligemma-tokenizer")).resolve()
START, END, ROUND_UPDATES, GROUPS = 1200, 2400, 40, 90
STARTER = Path(os.getenv("SO101_START_ADAPTER", PROJECT / "models/blockbox-001200")).resolve()
PYTHON = sys.executable
SEED_FILE = CONFIG / "blockbox-validation-seeds.txt"
SKIP_ODE = ROOT / "skip-ode"
WORKER = None


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def publish(path, data):
    staged = path.with_suffix(".tmp")
    staged.write_text(json.dumps(data, indent=2) + "\n")
    staged.replace(path)


def interrupt(signum, _frame):
    if WORKER is not None and WORKER.poll() is None:
        WORKER.terminate()
        WORKER.wait(timeout=30)
    raise SystemExit(128 + signum)


def wait_for_gpu():
    while True:
        try:
            memory = subprocess.check_output(
                ["nvidia-smi", "--query-gpu=memory.free", "--format=csv,noheader,nounits"],
                text=True,
            ).splitlines()[0]
            if int(memory) >= 14000:
                return
        except (OSError, subprocess.SubprocessError, ValueError, IndexError):
            memory = "unavailable"
        print("Waiting for GPU memory, available MiB:", memory, flush=True)
        time.sleep(30)


def run_worker(command, log):
    global WORKER
    wait_for_gpu()
    with log.open("a") as stream:
        WORKER = subprocess.Popen(command, cwd=PROJECT, stdout=stream, stderr=subprocess.STDOUT)
        try:
            if WORKER.wait():
                raise RuntimeError(f"Worker failed. See {log}")
        finally:
            WORKER = None


def inspect_checkpoint(folder, step):
    state = json.loads((folder / "rl_training.json").read_bytes())
    if state["updates"] != step or state.get("test_only"):
        raise ValueError(f"Incorrect checkpoint metadata: {folder}")
    for filename in ("adapter_model.safetensors", "optimizer.pt", "config.json"):
        if not (folder / filename).stat().st_size:
            raise ValueError(f"Empty checkpoint file: {folder / filename}")
    return digest(folder / "adapter_model.safetensors")


def evaluate(checkpoint, sha, step):
    seeds = SEED_FILE.read_text().split()
    if len(seeds) != 30 or len(set(seeds)) != 30:
        raise ValueError("Expected 30 unique paired validation cases")
    label = f"{step:06d}"
    output = ROOT / "validation" / label
    report = output / "report.json"
    if output.exists():
        d = json.loads(report.read_bytes()) if report.is_file() else {}
        if d.get("status") != "complete":
            output.rename(output.with_name(f"{label}.interrupted-{time.time_ns()}"))
    if not output.exists():
        run_worker(
            [PYTHON, "-u", str(SCRIPTS / "evaluate_blockbox_heldout.py"), "--offload-text-tables",
             "--base", str(BASE),
             "--adapter", str(checkpoint), "--adapter-sha256", sha,
             "--label", label, "--assets", "menagerie", "--tokenizer",
             str(TOKENIZER), "--calibration",
             "official_block_follower.json", "--output", str(output), "--execute-steps",
             "50", "--seeds", *seeds],
            ROOT / "validation" / f"{label}.log",
        )
    d = json.loads(report.read_bytes())
    rows = d["episodes"]
    if (d["status"] != "complete" or d["weights"]["adapter_sha256"] != sha
            or [str(row["seed"]) for row in rows] != seeds
            or d["successes"] != sum(row["success"] for row in rows)):
        raise ValueError(f"Invalid complete validation report: {report}")
    return d["successes"]


def prune_rollouts(round_dir):
    # Only payloads generated by this run are disposable. Preserve every
    # manifest, the policy/optimizer checkpoint, schedules and logs.
    round_dir = round_dir.resolve()
    if round_dir.parent != (ROOT / "rounds").resolve() or not (round_dir / "round-complete.json").is_file():
        raise ValueError("Refusing to clean an uncommitted round")
    for manifest in (round_dir / "accepted").glob("group-*/group.json"):
        if manifest.resolve().parent.parent != round_dir / "accepted":
            raise ValueError(f"Unexpected rollout manifest path: {manifest}")
        rows = json.loads(manifest.read_bytes())["records"]
        for row in rows:
            name = row["file"]
            if not re.fullmatch(r"chunk-[0-9]+\.pt\.gz", name):
                raise ValueError(f"Unexpected payload name: {name}")
            (manifest.parent / name).unlink(missing_ok=True)


def run():
    if (END - START) % ROUND_UPDATES:
        raise ValueError("Training target splits a round")
    (ROOT / "rounds").mkdir(exist_ok=True)
    (ROOT / "validation").mkdir(exist_ok=True)
    starter_hash = inspect_checkpoint(STARTER, START)
    checkpoint = STARTER
    sha = starter_hash
    results = []
    baseline_report = ROOT / "validation" / f"{START:06d}" / "report.json"
    if baseline_report.is_file():
        baseline = json.loads(baseline_report.read_bytes())
        if baseline.get("status") == "complete":
            if baseline["weights"]["adapter_sha256"] != starter_hash:
                raise ValueError("Validation baseline checkpoint changed")
            results.append({"step": START, "successes": baseline["successes"]})
    previous = None

    for index, begin in enumerate(range(START, END, ROUND_UPDATES), start=1):
        finish = begin + ROUND_UPDATES
        folder = ROOT / "rounds" / f"round-{index:03d}"
        folder.mkdir(exist_ok=True)
        target = folder / "checkpoints" / f"{finish:06d}"
        step_artifact = folder / "round-complete.json"
        if not step_artifact.is_file():
            if not target.is_dir():
                publish(ROOT / "status.json", {"phase": "collecting_or_training", "round": index,
                        "start_step": begin, "round_target": finish, "target": END,
                        "source_checkpoint": str(checkpoint)})
                print(f"Round {index}/30: {begin} -> {finish} from {checkpoint.name}", flush=True)
                run_worker(
                    [PYTHON, "-u", str(SCRIPTS / "train_blockbox_round.py"), "--base",
                     str(BASE), "--adapter",
                     str(checkpoint), "--adapter-sha256", sha, "--tokenizer",
                     str(TOKENIZER), "--output", str(folder),
                     "--groups", str(GROUPS), "--steps", str(ROUND_UPDATES), "--save-every",
                     str(ROUND_UPDATES), "--lr", "1e-6", "--start-step", str(begin),
                     "--scene-offset", str(61000 + (index - 1) * 1000),
                     "--validation-manifest", str(CONFIG / "blockbox-validation-scenes.json")],
                    folder / "run.log",
                )
            next_sha = inspect_checkpoint(target, finish)
            successes = None
            if not SKIP_ODE.exists():
                publish(ROOT / "status.json", {"phase": "validating", "round": index,
                                               "checkpoint": str(target), "target": END})
                if not results:
                    results.append({"step": START, "successes": evaluate(STARTER, starter_hash, START)})
                successes = evaluate(target, next_sha, finish)
            record = {"round": index, "step": finish, "validation_successes": successes,
                      "validation_episodes": 0 if successes is None else 30,
                      "source_sha256": sha, "adapter_sha256": next_sha}
            publish(step_artifact, record)
        else:
            record = json.loads(step_artifact.read_bytes())
            next_sha = inspect_checkpoint(target, finish)
            if (record["step"], record["source_sha256"], record["adapter_sha256"]) != (finish, sha, next_sha):
                raise ValueError(f"Round lineage changed: {folder}")
        checkpoint, sha = target, next_sha
        successes = record["validation_successes"]
        if successes is not None:
            results.append({"step": finish, "successes": successes})
        publish(ROOT / "validation-summary.json", results)
        detail = "ODE validation skipped" if successes is None else f"ODE validation {successes}/30"
        print(f"Round {index}/30 complete. {detail}", flush=True)
        if previous is not None:
            prune_rollouts(previous)
        previous = folder

    best = max(results, key=lambda row: row["successes"], default=None)
    publish(ROOT / "status.json", {"phase": "complete", "step": END, "additional_steps": END - START,
                                   "checkpoint": str(checkpoint), "best_validation": best})


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Run sequential B8 policy-refresh rounds")
    parser.add_argument("--check-only", action="store_true")
    parser.add_argument("--adopt-training-pid", type=int)
    options = parser.parse_args()
    if options.check_only:
        assert (END - START) // ROUND_UPDATES == 30
        assert inspect_checkpoint(STARTER, START)
        expected = [scene * 100 + repeat for scene in json.loads((CONFIG / "blockbox-validation-scenes.json").read_bytes())
                    for repeat in range(3)]
        assert list(map(int, SEED_FILE.read_text().split())) == expected and len(set(expected)) == 30
        print("Starting checkpoint and 30 paired validation cases verified.")
    else:
        ROOT.mkdir(parents=True, exist_ok=True)
        with (ROOT / "supervisor.lock").open("a") as lock:
            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
            signal.signal(signal.SIGTERM, interrupt)
            signal.signal(signal.SIGINT, interrupt)
            if options.adopt_training_pid is not None:
                process = Path(f"/proc/{options.adopt_training_pid}/cmdline")
                print(f"Waiting for existing trainer {options.adopt_training_pid}; ODE validation paused.", flush=True)
                while process.is_file():
                    try:
                        command = process.read_bytes()
                    except FileNotFoundError:
                        break
                    if str(SCRIPTS / "train_blockbox_round.py").encode() not in command:
                        break
                    time.sleep(2)
            run()
